--
-- 目的：导入从已授权组织参考数据中提取的 50 个真实单位。
-- 数据范围：只保留单位编码、名称、父级、层级和行政区划；联系人、电话、旧主键
--           和旧时间字段不进入本项目。
-- 层级修正：源数据中 330114 原挂象山县分局，330921/330922 原 parent_id=0；
--           按行政区划分别归入杭州支队和舟山支队，形成 1 总队 + 7 支队 + 42 大队。
-- 说明：使用普通 INSERT；如果任意单位编码已存在，迁移失败并停止，不静默覆盖。

CREATE TEMPORARY TABLE tmp_sys_unit_import (
    unit_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL
        COMMENT '待导入单位编码',
    unit_name VARCHAR(80) NOT NULL COMMENT '待导入单位名称',
    parent_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL
        COMMENT '待导入上级单位编码；一级单位为 NULL',
    unit_level TINYINT NOT NULL COMMENT '待导入层级',
    area_code VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL
        COMMENT '待导入行政区划代码',
    PRIMARY KEY (unit_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

