INSERT INTO sys_unit (unit_code, unit_name, parent_id, unit_level, area_code, status)
SELECT t.unit_code,
       t.unit_name,
       p.id,
       t.unit_level,
       t.area_code,
       'ENABLED'
  FROM tmp_sys_unit_import t
  LEFT JOIN sys_unit p ON p.unit_code = t.parent_code
 ORDER BY t.unit_level, t.unit_code;

